// Package main implements the OCI idempotent SQL schema migration runner.
// Migrations are tracked in public.goose_db_version and support -- +goose Up,
// -- +goose StatementBegin, and -- +goose StatementEnd directives.
package main

import (
	"context"
	"fmt"
	"io/fs"
	"log/slog"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

const versionTableDDL = `
CREATE TABLE IF NOT EXISTS public.goose_db_version (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	version_id BIGINT NOT NULL,
	is_applied BOOLEAN NOT NULL,
	tstamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_goose_db_version_version_id
	ON public.goose_db_version (version_id);
`

// migration represents a discovered SQL migration file and its parsed Up statements.
type migration struct {
	Version    int64
	RawPrefix  int64
	Filename   string
	Statements []string
}

type sqlDB interface {
	Exec(ctx context.Context, sql string, arguments ...any) error
	QueryApplied(ctx context.Context) (map[int64]bool, error)
	ApplyMigration(ctx context.Context, version int64, statements []string) error
}

type pgxStore struct {
	pool *pgxpool.Pool
}

func (s *pgxStore) Exec(ctx context.Context, sql string, arguments ...any) error {
	_, err := s.pool.Exec(ctx, sql, arguments...)
	return err
}

func (s *pgxStore) QueryApplied(ctx context.Context) (map[int64]bool, error) {
	rows, err := s.pool.Query(ctx, `SELECT version_id, is_applied FROM public.goose_db_version ORDER BY version_id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	applied := make(map[int64]bool)
	for rows.Next() {
		var versionID int64
		var isApplied bool
		if err := rows.Scan(&versionID, &isApplied); err != nil {
			return nil, err
		}
		applied[versionID] = isApplied
	}
	return applied, rows.Err()
}

func (s *pgxStore) ApplyMigration(ctx context.Context, version int64, statements []string) error {
	tx, err := s.pool.BeginTx(ctx, pgx.TxOptions{})
	if err != nil {
		return fmt.Errorf("begin migration tx %d: %w", version, err)
	}
	defer func() {
		_ = tx.Rollback(ctx)
	}()

	for i, stmt := range statements {
		if _, err := tx.Exec(ctx, stmt); err != nil {
			return fmt.Errorf("execute migration %d statement %d: %w", version, i+1, err)
		}
	}

	if _, err := tx.Exec(
		ctx,
		`INSERT INTO public.goose_db_version (version_id, is_applied, tstamp)
		 VALUES ($1, TRUE, NOW())
		 ON CONFLICT (version_id) DO UPDATE SET is_applied = TRUE, tstamp = NOW()`,
		version,
	); err != nil {
		return fmt.Errorf("record goose_db_version %d: %w", version, err)
	}

	return tx.Commit(ctx)
}

func main() {
	logger := slog.New(slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{Level: slog.LevelInfo}))
	slog.SetDefault(logger)

	dsn, err := resolveDatabaseURL()
	if err != nil {
		slog.Error("database configuration invalid", "error", err)
		os.Exit(1)
	}

	migrationsDir := strings.TrimSpace(os.Getenv("MIGRATIONS_DIR"))
	if migrationsDir == "" {
		migrationsDir = "scripts/migrations"
	}

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		slog.Error("failed to initialize pgx pool", "error", err)
		os.Exit(1)
	}
	defer pool.Close()

	if err := run(ctx, &pgxStore{pool: pool}, os.DirFS(migrationsDir)); err != nil {
		slog.Error("migration run failed", "error", err)
		os.Exit(1)
	}
	slog.Info("migrations completed cleanly", "dir", migrationsDir)
}

func resolveDatabaseURL() (string, error) {
	if raw := strings.TrimSpace(os.Getenv("DATABASE_URL")); raw != "" {
		return raw, nil
	}
	if p := strings.TrimSpace(os.Getenv("DATABASE_URL_FILE")); p != "" {
		b, err := os.ReadFile(p)
		if err != nil {
			return "", fmt.Errorf("read DATABASE_URL_FILE: %w", err)
		}
		if raw := strings.TrimSpace(string(b)); raw != "" {
			return raw, nil
		}
	}
	host := strings.TrimSpace(os.Getenv("PGHOST"))
	user := strings.TrimSpace(os.Getenv("PGUSER"))
	pass := os.Getenv("PGPASSWORD")
	dbName := strings.TrimSpace(os.Getenv("PGDATABASE"))
	port := strings.TrimSpace(os.Getenv("PGPORT"))
	if port == "" {
		port = "5432"
	}
	sslmode := strings.TrimSpace(os.Getenv("PGSSLMODE"))
	if sslmode == "" {
		sslmode = "require"
	}
	if host != "" && user != "" && dbName != "" {
		u := &url.URL{
			Scheme: "postgres",
			User:   url.UserPassword(user, pass),
			Host:   host + ":" + port,
			Path:   "/" + dbName,
		}
		q := u.Query()
		q.Set("sslmode", sslmode)
		u.RawQuery = q.Encode()
		return u.String(), nil
	}
	return "", fmt.Errorf("DATABASE_URL, DATABASE_URL_FILE, or PGHOST/PGUSER/PGDATABASE must be set")
}

func run(ctx context.Context, db sqlDB, migrationsFS fs.FS) error {
	migrations, err := loadMigrations(migrationsFS)
	if err != nil {
		return err
	}
	if err := db.Exec(ctx, versionTableDDL); err != nil {
		return fmt.Errorf("ensure goose_db_version table: %w", err)
	}
	applied, err := db.QueryApplied(ctx)
	if err != nil {
		return fmt.Errorf("query applied migrations: %w", err)
	}

	for _, m := range migrations {
		if applied[m.Version] {
			slog.Info("migration already applied", "version", m.Version, "file", m.Filename)
			continue
		}
		if len(m.Statements) == 0 {
			slog.Warn("skipping migration with zero Up statements", "version", m.Version, "file", m.Filename)
			continue
		}
		if err := db.ApplyMigration(ctx, m.Version, m.Statements); err != nil {
			return fmt.Errorf("apply %s (version %d): %w", m.Filename, m.Version, err)
		}
		slog.Info("applied migration", "version", m.Version, "file", m.Filename, "statements", len(m.Statements))
	}
	return nil
}

func loadMigrations(fsys fs.FS) ([]migration, error) {
	entries, err := fs.ReadDir(fsys, ".")
	if err != nil {
		return nil, fmt.Errorf("read migrations directory: %w", err)
	}

	var files []string
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".sql" {
			continue
		}
		files = append(files, entry.Name())
	}
	sort.Strings(files)

	var parsed []migration
	for _, name := range files {
		prefix, ok := parseVersionPrefix(name)
		if !ok {
			return nil, fmt.Errorf("migration file %q missing numeric version prefix", name)
		}
		raw, err := fs.ReadFile(fsys, name)
		if err != nil {
			return nil, fmt.Errorf("read migration %q: %w", name, err)
		}
		stmts := parseGooseUpStatements(string(raw))
		parsed = append(parsed, migration{
			RawPrefix:  prefix,
			Filename:   name,
			Statements: stmts,
		})
	}

	sort.SliceStable(parsed, func(i, j int) bool {
		if parsed[i].RawPrefix != parsed[j].RawPrefix {
			return parsed[i].RawPrefix < parsed[j].RawPrefix
		}
		return parsed[i].Filename < parsed[j].Filename
	})

	// Assign monotonic unique version IDs even when legacy files share a numeric prefix
	// (for example 002-firmware-cosign-signature.sql and 002-monitoring-role.sql).
	var prevVersion int64
	for i := range parsed {
		v := parsed[i].RawPrefix
		if v <= prevVersion {
			v = prevVersion + 1
		}
		parsed[i].Version = v
		prevVersion = v
	}

	return parsed, nil
}

func parseVersionPrefix(filename string) (int64, bool) {
	parts := strings.SplitN(filename, "-", 2)
	if len(parts) < 2 {
		parts = strings.SplitN(filename, "_", 2)
	}
	if len(parts) < 1 || parts[0] == "" {
		return 0, false
	}
	n, err := strconv.ParseInt(parts[0], 10, 64)
	if err != nil || n <= 0 {
		return 0, false
	}
	return n, true
}

// parseGooseUpStatements extracts executable SQL statements from the Up section.
// If no -- +goose Up marker exists, the entire file is treated as Up statements.
func parseGooseUpStatements(sqlText string) []string {
	lines := strings.Split(strings.ReplaceAll(sqlText, "\r\n", "\n"), "\n")

	hasUpMarker := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "-- +goose Up" {
			hasUpMarker = true
			break
		}
	}

	inUp := !hasUpMarker
	inBlock := false
	var buf strings.Builder
	var statements []string

	flush := func() {
		stmt := strings.TrimSpace(buf.String())
		buf.Reset()
		if stmt != "" {
			statements = append(statements, stmt)
		}
	}

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		switch trimmed {
		case "-- +goose Up":
			inUp = true
			continue
		case "-- +goose Down":
			flush()
			inUp = false
			continue
		case "-- +goose StatementBegin":
			if inUp {
				flush()
				inBlock = true
			}
			continue
		case "-- +goose StatementEnd":
			if inUp {
				flush()
				inBlock = false
			}
			continue
		}

		if !inUp {
			continue
		}
		if strings.HasPrefix(trimmed, "--") && buf.Len() == 0 {
			continue
		}

		if buf.Len() > 0 {
			buf.WriteByte('\n')
		}
		buf.WriteString(line)

		if !inBlock && strings.HasSuffix(trimmed, ";") {
			flush()
		}
	}
	flush()
	return statements
}
