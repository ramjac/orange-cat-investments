package reporting

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"time"
)

// GenerateExecutiveCSV renders an ExecutiveReport into RFC 4180 CSV format.
func GenerateExecutiveCSV(r *ExecutiveReport) (string, error) {
	if r == nil {
		return "", fmt.Errorf("report is nil")
	}

	var buf bytes.Buffer
	w := csv.NewWriter(&buf)

	headers := []string{"Category", "Metric", "Value", "Unit", "Notes"}
	if err := w.Write(headers); err != nil {
		return "", err
	}

	fin := r.FinancialSummary
	wf := r.WorkforceSummary

	records := [][]string{
		{"Financial", "Total Revenue", fmt.Sprintf("%.2f", fin.TotalRevenue), fin.Currency, "Investment advisory fees and feline alpha trading returns"},
		{"Financial", "Operating Expenses", fmt.Sprintf("%.2f", fin.OperatingExpenses), fin.Currency, "Facilities cloud infra catnip and hardware telemetry"},
		{"Financial", "Payroll Expenses", fmt.Sprintf("%.2f", fin.PayrollExpenses), fin.Currency, "Human salaries and feline executive compensation"},
		{"Financial", "Net Profit", fmt.Sprintf("%.2f", fin.NetProfit), fin.Currency, "Net operating income after all expenses"},
		{"Financial", "Operational Burn", fmt.Sprintf("%.2f", fin.OperationalBurn), fin.Currency, "Monthly cash outflow (operating + payroll)"},
		{"Financial", "Cash Reserves", fmt.Sprintf("%.2f", fin.CashReserves), fin.Currency, "Liquid reserves across authorized commercial accounts"},
		{"Financial", "Runway Months", fmt.Sprintf("%.2f", fin.RunwayMonths), "Months", "Cash reserves divided by monthly burn rate"},
		{"Workforce", "Total Headcount", fmt.Sprintf("%d", wf.TotalHeadcount), "Staff", "All active corporate human staff and feline analysts"},
		{"Workforce", "Human Headcount", fmt.Sprintf("%d", wf.HumanHeadcount), "Staff", "Full-time engineering ops hr and veterinary staff"},
		{"Workforce", "Feline Headcount", fmt.Sprintf("%d", wf.FelineHeadcount), "Executives", "Executive feline leadership and quantitative trading talent"},
		{"Workforce", "Attendance Rate", fmt.Sprintf("%.2f", wf.AttendanceRate), "Percent", "Shift attendance verified through badge and timesheets"},
		{"Workforce", "Total Hours Worked", fmt.Sprintf("%.2f", wf.TotalHoursWorked), "Hours", "Combined human and feline logged duty hours"},
		{"Workforce", "Overtime Hours", fmt.Sprintf("%.2f", wf.OvertimeHours), "Hours", "Additional shift and on-call duty hours logged"},
		{"Workforce", "Timesheets Approved", fmt.Sprintf("%d", wf.TimesheetsApproved), "Timesheets", "Workforce timesheets reviewed and approved by management"},
		{"Workforce", "Pending Reviews", fmt.Sprintf("%d", wf.PendingReviews), "Reviews", "Active performance appraisal and wellness audit cycles"},
		{"Workforce", "Open Incidents", fmt.Sprintf("%d", wf.OpenIncidents), "Incidents", "Workplace safety incident tickets pending resolution"},
		{"Metadata", "Report ID", r.ReportID, "ID", "Unique executive report identifier"},
		{"Metadata", "Period", r.Period, "Period", "Monthly reporting cycle"},
		{"Metadata", "Generated By", r.GeneratedBy, "Principal", "Reporting service or authenticated actor"},
		{"Metadata", "Generated At", r.CreatedAt.Format(time.RFC3339), "Timestamp", "Report generation timestamp"},
		{"Metadata", "WebDAV PDF Path", r.WebDAVPathPDF, "Path", "Nextcloud compliance archive destination"},
		{"Metadata", "WebDAV CSV Path", r.WebDAVPathCSV, "Path", "Nextcloud compliance archive destination"},
	}

	for _, row := range records {
		sanitizedRow := make([]string, len(row))
		for i, col := range row {
			sanitizedRow[i] = sanitizeCSVField(col)
		}
		if err := w.Write(sanitizedRow); err != nil {
			return "", err
		}
	}

	w.Flush()
	if err := w.Error(); err != nil {
		return "", err
	}

	return buf.String(), nil
}

// sanitizeCSVField neutralizes spreadsheet formula injection risks (OWASP CSV Injection).
// If a string starts with '=', '+', '-', '@', '\t', or '\r', it is prefixed with a single quote.
func sanitizeCSVField(val string) string {
	if len(val) == 0 {
		return val
	}
	switch val[0] {
	case '=', '+', '-', '@', '\t', '\r':
		return "'" + val
	default:
		return val
	}
}

