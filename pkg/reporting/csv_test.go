func TestGenerateExecutiveCSV_Valid(t *testing.T) {
	r := sampleReport()
	csvStr, err := GenerateExecutiveCSV(r)
	require.NoError(t, err)
	assert.NotEmpty(t, csvStr)

	reader := csv.NewReader(strings.NewReader(csvStr))
	records, err := reader.ReadAll()
	require.NoError(t, err)

	// Check header
	assert.Equal(t, []string{"Category", "Metric", "Value", "Unit", "Notes"}, records[0])

	// Verify all records count (1 header + 22 records = 23 rows)
	require.Len(t, records, 23)

	recordMap := make(map[string][]string)
	for _, rec := range records[1:] {
		key := rec[0] + ":" + rec[1]
		recordMap[key] = rec
	}

	// Financial assertions
	assert.Equal(t, []string{"Financial", "Total Revenue", "1350000.00", "USD", "Investment advisory fees and feline alpha trading returns"}, recordMap["Financial:Total Revenue"])
	assert.Equal(t, []string{"Financial", "Operating Expenses", "320000.00", "USD", "Facilities cloud infra catnip and hardware telemetry"}, recordMap["Financial:Operating Expenses"])
	assert.Equal(t, []string{"Financial", "Runway Months", "13.06", "Months", "Cash reserves divided by monthly burn rate"}, recordMap["Financial:Runway Months"])

	// Workforce assertions
	assert.Equal(t, []string{"Workforce", "Total Headcount", "12", "Staff", "All active corporate human staff and feline analysts"}, recordMap["Workforce:Total Headcount"])
	assert.Equal(t, []string{"Workforce", "Attendance Rate", "99.40", "Percent", "Shift attendance verified through badge and timesheets"}, recordMap["Workforce:Attendance Rate"])

	// Metadata assertions
	assert.Equal(t, []string{"Metadata", "Report ID", "rep-2026-10", "ID", "Unique executive report identifier"}, recordMap["Metadata:Report ID"])
	assert.Equal(t, []string{"Metadata", "Period", "2026-10", "Period", "Monthly reporting cycle"}, recordMap["Metadata:Period"])
	assert.Equal(t, []string{"Metadata", "Generated At", r.CreatedAt.Format(time.RFC3339), "Timestamp", "Report generation timestamp"}, recordMap["Metadata:Generated At"])
}

func TestSanitizeCSVField(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected string
	}{
		{
			name:     "Empty string",
			input:    "",
			expected: "",
		},
		{
			name:     "Normal safe text",
			input:    "Normal Text 123",
			expected: "Normal Text 123",
		},
		{
			name:     "Formula starting with =",
			input:    "=SUM(A1:A10)",
			expected: "'=SUM(A1:A10)",
		},
		{
			name:     "Formula starting with +",
			input:    "+12345",
			expected: "'+12345",
		},
		{
			name:     "Formula starting with -",
			input:    "-cmd|' /C calc'!A0",
			expected: "'-cmd|' /C calc'!A0",
		},
		{
			name:     "Formula starting with @",
			input:    "@SUM(1,2)",
			expected: "'@SUM(1,2)",
		},
		{
			name:     "Tab prefix",
			input:    "\tval",
			expected: "'\tval",
		},
		{
			name:     "Carriage return prefix",
			input:    "\rval",
			expected: "'\rval",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := sanitizeCSVField(tt.input)
			assert.Equal(t, tt.expected, got)
		})
	}
}

func TestGenerateExecutiveCSV_FormulaSanitizationInReport(t *testing.T) {
	r := &ExecutiveReport{
		ReportID:         "=DANGEROUS()",
		Period:           "+2026-10",
		GeneratedBy:      "@admin",
		FinancialSummary: frappe.FinancialMetrics{Currency: "\tUSD"},
		CreatedAt:        time.Date(2026, 10, 1, 0, 0, 0, 0, time.UTC),
	}

	csvStr, err := GenerateExecutiveCSV(r)
	require.NoError(t, err)

	reader := csv.NewReader(strings.NewReader(csvStr))
	records, err := reader.ReadAll()
	require.NoError(t, err)

	recordMap := make(map[string]string)
	for _, rec := range records[1:] {
		recordMap[rec[1]] = rec[2]
	}

	assert.Equal(t, "'=DANGEROUS()", recordMap["Report ID"])
	assert.Equal(t, "'+2026-10", recordMap["Period"])
	assert.Equal(t, "'@admin", recordMap["Generated By"])
}
