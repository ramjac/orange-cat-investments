func TestGenerateExecutiveCSV(t *testing.T) {
	r := sampleReport()
	csvStr, err := GenerateExecutiveCSV(r)
	require.NoError(t, err)
	assert.NotEmpty(t, csvStr)

	// Verify RFC 4180 parsing
	reader := csv.NewReader(strings.NewReader(csvStr))
	records, err := reader.ReadAll()
	require.NoError(t, err)
	assert.GreaterOrEqual(t, len(records), 20)

	// Check header
	assert.Equal(t, []string{"Category", "Metric", "Value", "Unit", "Notes"}, records[0])

	// Check specific metrics
	foundRevenue := false
	foundHeadcount := false
	for _, rec := range records {
		if rec[1] == "Total Revenue" {
			foundRevenue = true
			assert.Equal(t, "1350000.00", rec[2])
			assert.Equal(t, "USD", rec[3])
		}
		if rec[1] == "Total Headcount" {
			foundHeadcount = true
			assert.Equal(t, "12", rec[2])
			assert.Equal(t, "Staff", rec[3])
		}
	}
	assert.True(t, foundRevenue, "Total Revenue should exist in CSV")
	assert.True(t, foundHeadcount, "Total Headcount should exist in CSV")
}

func TestGenerateExecutiveCSV_FormulaInjectionSanitization(t *testing.T) {
	r := sampleReport()
	r.GeneratedBy = "=cmd|' /C calc'!A0"
	r.Period = "+2026-10"
	r.ReportID = "@malicious-id"

	csvStr, err := GenerateExecutiveCSV(r)
	require.NoError(t, err)

	reader := csv.NewReader(strings.NewReader(csvStr))
	records, err := reader.ReadAll()
	require.NoError(t, err)

	for _, rec := range records {
		if rec[1] == "Generated By" {
			assert.Equal(t, "'=cmd|' /C calc'!A0", rec[2], "Formula prefix '=' must be prepended with single quote")
		}
		if rec[1] == "Period" {
			assert.Equal(t, "'+2026-10", rec[2], "Formula prefix '+' must be prepended with single quote")
		}
		if rec[1] == "Report ID" {
			assert.Equal(t, "'@malicious-id", rec[2], "Formula prefix '@' must be prepended with single quote")
		}
	}
}


func TestEscapePDF(t *testing.T) {
	tests := []struct {
		name     string
		input    string
		expected string
	}{
		{
			name:     "plain string",
			input:    "Hello World",
			expected: "Hello World",
		},
		{
			name:     "string with parentheses",
			input:    "Report (Q1) - Draft",
			expected: `Report \(Q1\) - Draft`,
		},
		{
			name:     "string with backslashes",
			input:    `C:\Reports\Executive`,
			expected: `C:\\Reports\\Executive`,
		},
		{
			name:     "string with mixed backslashes and parentheses",
			input:    `Path\(2026)\pdf`,
			expected: `Path\\\(2026\)\\pdf`,
		},
		{
			name:     "empty string",
			input:    "",
			expected: "",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.expected, escapePDF(tt.input))
		})
	}
}

